import { useState, type FormEvent } from "react";
import { KeyRound, ShieldAlert } from "lucide-react";
import { Button, Field } from "@/components/ui/primitives";
import { Modal } from "@/components/ui/overlays";
import { useToast } from "@/components/ui/toast";
import { FormAlert, PasswordInput, PasswordRules } from "./AuthParts";
import { hasErrors, vConfirm, vNewPassword } from "@/lib/studentValidation";
import { useStudentAuth } from "@/hooks/useStudentAuth";

interface Props {
  open: boolean;
  onClose: () => void;
  canDismiss?: boolean;
}

export function MustChangePasswordModal({ open, onClose, canDismiss = true }: Props) {
  const { updatePassword } = useStudentAuth();
  const toast = useToast();

  const [password, setPassword] = useState("");
  const [confirm, setConfirm] = useState("");
  const [currentPassword, setCurrentPassword] = useState("");
  const [errors, setErrors] = useState<{ password?: string; confirm?: string }>({});
  const [formError, setFormError] = useState<string | null>(null);
  const [submitting, setSubmitting] = useState(false);

  const handleSubmit = async (e: FormEvent) => {
    e.preventDefault();
    const next = { password: vNewPassword(password), confirm: vConfirm(password, confirm) };
    setErrors(next);
    setFormError(null);
    if (hasErrors(next)) return;

    setSubmitting(true);
    try {
      await updatePassword(password, currentPassword || undefined);
      toast.success("Password changed successfully!");
      setPassword("");
      setConfirm("");
      setCurrentPassword("");
      onClose();
    } catch (err) {
      setFormError(err instanceof Error ? err.message : "Failed to update password. Please try again.");
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <Modal
      open={open}
      onClose={() => {
        if (canDismiss) onClose();
      }}
      size="md"
      title={
        <div className="flex items-center gap-2.5">
          <div className="flex h-9 w-9 items-center justify-center rounded-xl bg-amber-500/10 text-amber-500">
            <KeyRound className="h-5 w-5" />
          </div>
          <div>
            <span className="font-heading text-lg font-bold">Reset Your Password</span>
          </div>
        </div>
      }
      description="You are currently signed in with a temporary password sent via email. For your security, please choose a personal password."
    >
      <form onSubmit={handleSubmit} noValidate className="space-y-4">
        {formError && <FormAlert tone="error">{formError}</FormAlert>}

        <div className="rounded-xl border border-amber-500/20 bg-amber-500/5 p-3.5 text-xs text-amber-800 dark:text-amber-300 flex items-start gap-2.5">
          <ShieldAlert className="h-4 w-4 shrink-0 mt-0.5 text-amber-500" />
          <div>
            <p className="font-semibold">Security Requirement</p>
            <p className="mt-0.5 text-muted leading-relaxed">
              Your temporary password was generated by the administration. Resetting it now ensures only you have access to your account and classes.
            </p>
          </div>
        </div>

        <Field label="New password" error={errors.password}>
          <PasswordInput
            autoComplete="new-password"
            placeholder="Create your new password"
            value={password}
            invalid={Boolean(errors.password)}
            onChange={(e) => {
              setPassword(e.target.value);
              if (errors.password) setErrors((p) => ({ ...p, password: vNewPassword(e.target.value) }));
            }}
            onBlur={() => setErrors((p) => ({ ...p, password: vNewPassword(password) }))}
          />
          <PasswordRules value={password} />
        </Field>

        <Field label="Confirm new password" error={errors.confirm}>
          <PasswordInput
            autoComplete="new-password"
            placeholder="Repeat your new password"
            value={confirm}
            invalid={Boolean(errors.confirm)}
            onChange={(e) => {
              setConfirm(e.target.value);
              if (errors.confirm) setErrors((p) => ({ ...p, confirm: vConfirm(password, e.target.value) }));
            }}
            onBlur={() => setErrors((p) => ({ ...p, confirm: vConfirm(password, confirm) }))}
          />
        </Field>

        <div className="flex items-center justify-end gap-3 pt-3 border-t border-line">
          {canDismiss && (
            <Button
              type="button"
              variant="outline"
              disabled={submitting}
              onClick={onClose}
            >
              Remind me later
            </Button>
          )}
          <Button type="submit" disabled={submitting}>
            <KeyRound className="h-4 w-4" />
            {submitting ? "Updating..." : "Set New Password"}
          </Button>
        </div>
      </form>
    </Modal>
  );
}
